"""Generate the home desk's non-secret settings from `fly.live.toml` [env].

Usage:
    python scripts/home_env_from_fly.py            # (re)write deploy/home/live.env.example
    python scripts/home_env_from_fly.py --check    # exit 1 if the committed file differs

Secrets rule. `[env]` is by definition the non-secret half (Fly secrets never
appear in the toml), so a secret-shaped key there is a mistake and the
generator REFUSES it (exit 2, names the key) instead of copying it. A key is
secret-shaped if it ends in _KEY, _TOKEN, _SECRET, _B64, contains PASSWORD,
ends in WEBHOOK_URL, or is one of the credential names `.env.example` carries
(it has no machine-readable secret marker; those names are listed below).
Secrets live in a separate gitignored `.env.live-home`.

Quoting follows Docker compose's env_file: unquoted values end at ` #`, so a
value with a space, `#`, `$`, a quote or a backslash is written in single
quotes, which compose reads literally (no interpolation). A value holding a
single quote or newline cannot be written that way and is refused.

Does not establish: that the home desk's other (secret) settings are present.
"""
from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_TOML = ROOT / "fly.live.toml"
DEFAULT_OUT = ROOT / "deploy" / "home" / "live.env.example"

SECRET_SUFFIXES = ("_KEY", "_TOKEN", "_SECRET", "_B64", "WEBHOOK_URL")
SECRET_SUBSTRINGS = ("PASSWORD",)
# Credential names from `.env.example` whose names the suffix rules alone miss.
SECRET_NAMES = frozenset({
    "KALSHI_PRIVATE_KEY_PATH", "KALSHI_API_KEY", "ODDS_API_KEY",
    "APP_AUTH_TOKEN", "ANTHROPIC_API_KEY", "DISCORD_WEBHOOK_URL",
    "DISCORD_BOT_TOKEN",
})

HEADER = (
    "# GENERATED by scripts/home_env_from_fly.py from fly.live.toml [env].\n"
    "# DO NOT EDIT: change fly.live.toml and re-run the script.\n"
    "# Non-secret settings only; secrets live in the gitignored .env.live-home.\n"
)


class SecretKeyError(ValueError):
    pass


def looks_secret(key: str) -> bool:
    k = key.upper()
    return (
        k in SECRET_NAMES
        or k.endswith(SECRET_SUFFIXES)
        or any(s in k for s in SECRET_SUBSTRINGS)
    )


def quote(key: str, value: str) -> str:
    if "'" in value or "\n" in value or "\r" in value:
        raise ValueError(
            f"{key}: value has a quote or newline; cannot be written to env_file"
        )
    if any(c in value for c in " \t#$\"\\") or value != value.strip():
        return f"'{value}'"
    return value


def generate(toml_path: Path) -> str:
    with open(toml_path, "rb") as fh:
        env = tomllib.load(fh).get("env", {})
    lines = []
    for key in sorted(env):
        if looks_secret(key):
            raise SecretKeyError(f"refusing secret-shaped key in [env]: {key}")
        value = env[key]
        if not isinstance(value, str):
            raise ValueError(f"{key}: [env] value is not a string")
        lines.append(f"{key}={quote(key, value)}\n")
    return HEADER + "".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--toml", type=Path, default=DEFAULT_TOML)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    try:
        text = generate(args.toml)
    except (SecretKeyError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 2
    if args.check:
        have = args.out.read_bytes().decode() if args.out.exists() else None
        if have != text:
            print(
                f"{args.out} differs from {args.toml}; re-run without --check",
                file=sys.stderr,
            )
            return 1
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(text.encode())
    n = text.count("\n") - HEADER.count("\n")
    print(f"wrote {args.out} ({n} keys)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
